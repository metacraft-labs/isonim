#!/usr/bin/env bash
# Installs this repository's committed .pre-commit-config.yaml as its git hooks.
#
# The flake provides the tools, the committed config provides the rules
# (metacraft-dev-guidelines repo-requirements.md 4.1): each hook runs the
# committed config with the flake's pre-commit. git-hooks.nix's own installer
# cannot do this -- it refuses to replace a non-symlink .pre-commit-config.yaml
# and then installs nothing at all.
#
# Reprobuild owns the hook dispatchers; this script owns only the local checks.
# Where a dispatcher holds a hook slot, the check is written as
# `<hook>.repro-local`, which the dispatcher runs.
#
#   bash scripts/install-git-hooks.sh /path/to/pre-commit
set -euo pipefail
pre_commit=$1
config=.pre-commit-config.yaml
marker='# git-hooks: generated by scripts/install-git-hooks.sh'
git rev-parse --git-dir >/dev/null 2>&1 || exit 0
repo_root=$(git rev-parse --show-toplevel)
config_path="$repo_root/$config"
# A /nix/store symlink at that path is a config git-hooks.nix generated before
# the file was committed; the committed file replaces it.
if [[ -L $config_path && $(readlink "$config_path") == /nix/store/* ]] &&
	git -C "$repo_root" cat-file -e "HEAD:$config" 2>/dev/null; then
	rm -f "$config_path"
	git -C "$repo_root" checkout HEAD -- "$config"
fi
if [[ ! -f $config_path || -L $config_path ]]; then
	echo "git-hooks: $config_path is not the committed config; restore it with" \
		"'git checkout HEAD -- $config'. No hooks were installed." >&2
	exit 0
fi
# The hook types the config asks for (`default_install_hook_types`, flow or
# block list); pre-commit's own default is `pre-commit` alone. Installing only
# those leaves every other slot -- a git-lfs pre-push, say -- to its owner.
stages=()
while IFS= read -r stage; do
	[[ -n $stage ]] && stages+=("$stage")
done < <(awk '
	/^default_install_hook_types:/ {
		line = $0; sub(/^[^:]*:[ \t]*/, "", line)
		if (line ~ /^\[/) { gsub(/[][ \t'"'"'"]/, "", line); n = split(line, a, ","); for (i = 1; i <= n; i++) print a[i]; exit }
		block = 1; next
	}
	block && /^[ \t]*-/ { line = $0; sub(/^[ \t]*-[ \t]*/, "", line); gsub(/[ \t'"'"'"]/, "", line); sub(/#.*/, "", line); print line; next }
	block && /^[^ \t#]/ { exit }
' "$config_path")
((${#stages[@]})) || stages=(pre-commit)
# Resolve the directory, not the final component: Git dereferences hook symlinks.
hooks_dir=$(git rev-parse --path-format=absolute --git-path hooks)
targets=()
# Validate every destination before changing any hook.
for stage in "${stages[@]}"; do
	hook="$hooks_dir/$stage"
	# A hook this installer must not overwrite is reported and left, and the
	# stage is skipped: the dev-shell handoff never fails the shell, and
	# `repro hooks ensure --vcs` reconciles what is left
	# (reprobuild-pm spec/CLI/hooks.md, "Dev-shell handoff").
	if [[ -L $hook ]]; then
		echo "git-hooks: $hook is a symlink; leaving it and not installing the $stage" \
			"check. Run 'repro hooks ensure --vcs' to reconcile." >&2
		targets+=("")
		continue
	fi
	if [[ -f $hook ]] && grep -q 'reprobuild hook dispatcher' "$hook"; then
		hook="$hook.repro-local"
	fi
	if [[ -L $hook ]]; then
		echo "git-hooks: $hook is a symlink; leaving it and not installing the $stage" \
			"check. Run 'repro hooks ensure --vcs' to reconcile." >&2
		targets+=("")
		continue
	fi
	# A hook in the slot itself may be a pre-commit or prek shim. A chained
	# `.repro-local` is replaced only by this script's own output (the marker):
	# another generator's shim there is two hooks with different content, which
	# `repro hooks ensure` refuses to reconcile and so does this script.
	if [[ $hook == *.repro-local ]]; then
		replaceable="^$marker"
	else
		replaceable="^(# File generated by (pre-commit|prek)|$marker)"
	fi
	if [[ -e $hook ]] && { [[ ! -f $hook ]] || ! grep -Eq "$replaceable" "$hook"; }; then
		echo "git-hooks: $hook is not this installer's shim (hand-written, or another" \
			"generator's); leaving it and not installing the $stage check. Run" \
			"'repro hooks ensure --vcs' to reconcile, or delete it if it is a stale" \
			"pre-commit or prek shim, and re-enter the dev shell." >&2
		targets+=("")
		continue
	fi
	targets+=("$hook")
done
mkdir -p "$hooks_dir"
for index in "${!stages[@]}"; do
	hook="${targets[$index]}"
	[[ -n $hook ]] || continue
	{
		printf '%s\n' '#!/usr/bin/env bash' "$marker"
		# hook-impl retains pre-push ref selection, stdin, remote arguments and
		# the framework's legitimate .legacy hook chain. `run` does not.
		printf 'exec %q hook-impl --config %q --hook-type %q --hook-dir %q -- "$@"\n' \
			"$pre_commit" "$config" "${stages[$index]}" "$hooks_dir"
	} >"$hook"
	chmod +x "$hook"
done

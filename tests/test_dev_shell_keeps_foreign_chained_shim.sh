#!/usr/bin/env bash
# A dev shell never overwrites another generator's shim chained as
# `<hook>.repro-local`.
#
# `repro hooks ensure` refuses two shims from different generators or template
# revisions (reprobuild-pm spec/CLI/hooks.md, "Reclaiming the slot"), and the
# dev-shell handoff applies the same rule. This test drives the two pieces of
# this repository that write a chained hook, in a scratch repository whose
# dispatchers are the ones the `repro` on PATH installs (nothing is mocked):
#   - the installer, scripts/install-git-hooks.sh: its own shim at
#     `.repro-local` is replaced, a pre-commit framework shim there is reported and left
#     byte-identical, without failing the shell;
#   - the handoff loop of flake.nix's `ownRepoOnly`, extracted verbatim from
#     the flake: a pre-commit shim displaced to the slot is chained over a
#     previous shim of the same generator and template, and over nothing else.
# The shims are written the way pre-commit and prek write them: a
# `# File generated by <tool>:` line and an `# ID:` line.
#
# Needs `repro` on PATH; without it the test fails, it does not skip.
#
#   bash tests/test_dev_shell_keeps_foreign_chained_shim.sh
set -euo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fail() { echo "FAIL: $*" >&2; exit 1; }
command -v repro >/dev/null || fail "repro is not on PATH (prerequisite, not a skip)"
SCRATCH="$(mktemp -d)"
trap 'rm -rf "$SCRATCH"' EXIT
GIT=(git -c user.name=test -c user.email=test@example.invalid -c commit.gpgsign=false)

new_repo() {
  rm -rf "$1"; git init -q "$1"
  (cd "$1" && "${GIT[@]}" commit -q --allow-empty -m init)
  repro hooks ensure --vcs "$1" >/dev/null 2>&1 || fail "repro hooks ensure --vcs failed"
  hooks="$(git -C "$1" rev-parse --path-format=absolute --git-path hooks)"
  grep -q 'reprobuild hook dispatcher' "$hooks/pre-commit" || fail "setup: no pre-commit dispatcher"
}
shim() { # shim <tool> <id> <path-marker>
  printf '#!/usr/bin/env bash\n# File generated by %s: DO NOT EDIT\n# ID: %s\nINSTALL_PYTHON=%s\n' "$1" "$2" "$3"
}

extract_loop() {
  python3 - "$REPO/flake.nix" <<'PY'
import re, sys
s = open(sys.argv[1]).read()
m = re.search(r'^( *)for _legacy in .*?^\1done$', s, re.M | re.S)
assert m, "handoff loop not found in flake.nix"
print(m.group(0).replace("''${", "${").replace("${pkgs.git}/bin/git", "git"))
PY
}
extract_loop >"$SCRATCH/loop.sh"
[ -s "$SCRATCH/loop.sh" ] || fail "could not extract the handoff loop"
handoff() { (cd "$1" && _hooks="$hooks" bash "$SCRATCH/loop.sh") 2>"$SCRATCH/err"; }
displace() { # the state `pre-commit install` leaves: shim in the slot, dispatcher at .legacy
  mv "$hooks/pre-commit" "$hooks/pre-commit.legacy"
  shim "$1" "$2" /new >"$hooks/pre-commit"; chmod +x "$hooks/pre-commit"
}

echo "== handoff: another generator's shim at .repro-local is left alone"
new_repo "$SCRATCH/a"
shim prek 11111111 /old >"$hooks/pre-commit.repro-local"
cp "$hooks/pre-commit.repro-local" "$SCRATCH/kept"
displace pre-commit 22222222
handoff "$SCRATCH/a"
cmp -s "$hooks/pre-commit.repro-local" "$SCRATCH/kept" || fail "another generator's .repro-local was overwritten"
grep -q "another generator's shim" "$SCRATCH/err" || fail "no report: $(cat "$SCRATCH/err")"
grep -q 'reprobuild hook dispatcher' "$hooks/pre-commit.legacy" || fail "dispatcher moved although the shims differ"

echo "== handoff: a previous shim of the same generator and template is replaced"
new_repo "$SCRATCH/b"
shim pre-commit 22222222 /old >"$hooks/pre-commit.repro-local"
displace pre-commit 22222222
handoff "$SCRATCH/b"
grep -q 'INSTALL_PYTHON=/new' "$hooks/pre-commit.repro-local" || fail "same-generator shim not replaced"
grep -q 'reprobuild hook dispatcher' "$hooks/pre-commit" || fail "dispatcher not restored"
[ ! -e "$hooks/pre-commit.legacy" ] || fail ".legacy left behind"

echo "== handoff: a different template revision of the same generator is left alone"
new_repo "$SCRATCH/c"
shim pre-commit 33333333 /old >"$hooks/pre-commit.repro-local"
cp "$hooks/pre-commit.repro-local" "$SCRATCH/kept"
displace pre-commit 22222222
handoff "$SCRATCH/c"
cmp -s "$hooks/pre-commit.repro-local" "$SCRATCH/kept" || fail "other template revision overwritten"

echo "== installer: another generator's shim at .repro-local is left and reported, its own is replaced"
new_repo "$SCRATCH/d"
printf 'repos: []\n' >"$SCRATCH/d/.pre-commit-config.yaml"
shim pre-commit 22222222 /old >"$hooks/pre-commit.repro-local"
cp "$hooks/pre-commit.repro-local" "$SCRATCH/kept"
(cd "$SCRATCH/d" && bash "$REPO/scripts/install-git-hooks.sh" /bin/true) 2>"$SCRATCH/err" \
  || fail "the installer failed the shell over a foreign .repro-local: $(cat "$SCRATCH/err")"
grep -q 'repro hooks ensure --vcs' "$SCRATCH/err" || fail "the installer reported nothing"
cmp -s "$hooks/pre-commit.repro-local" "$SCRATCH/kept" || fail "the installer modified the foreign .repro-local"
rm "$hooks/pre-commit.repro-local"
(cd "$SCRATCH/d" && bash "$REPO/scripts/install-git-hooks.sh" /bin/true) || fail "the installer failed on a free .repro-local"
grep -q 'git-hooks: generated by scripts/install-git-hooks.sh' "$hooks/pre-commit.repro-local" || fail "installer wrote no shim"
(cd "$SCRATCH/d" && bash "$REPO/scripts/install-git-hooks.sh" /bin/true) || fail "the installer cannot replace its own shim"
rm "$hooks/pre-commit.repro-local"; ln -s /bin/true "$hooks/pre-commit.repro-local"
(cd "$SCRATCH/d" && bash "$REPO/scripts/install-git-hooks.sh" /bin/true) 2>"$SCRATCH/err" \
  || fail "the installer failed the shell over a symlinked .repro-local: $(cat "$SCRATCH/err")"
[ "$(readlink "$hooks/pre-commit.repro-local")" = /bin/true ] || fail "the symlinked .repro-local was replaced"
echo "== installer: a hand-written hook in a slot with no dispatcher is left and reported"
new_repo "$SCRATCH/e"
printf 'repos: []\n' >"$SCRATCH/e/.pre-commit-config.yaml"
printf '#!/bin/sh\necho mine\n' >"$hooks/pre-commit.mine"
mv "$hooks/pre-commit" "$hooks/pre-commit.dispatcher"; mv "$hooks/pre-commit.mine" "$hooks/pre-commit"
cp "$hooks/pre-commit" "$SCRATCH/kept"
(cd "$SCRATCH/e" && bash "$REPO/scripts/install-git-hooks.sh" /bin/true) 2>"$SCRATCH/err" \
  || fail "the installer failed the shell over a hand-written hook: $(cat "$SCRATCH/err")"
cmp -s "$hooks/pre-commit" "$SCRATCH/kept" || fail "a hand-written hook was overwritten"
grep -q 'repro hooks ensure --vcs' "$SCRATCH/err" || fail "the installer reported nothing"

echo "PASS: no dev-shell step overwrites another generator's chained shim"

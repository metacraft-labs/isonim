"""Run the genuine compiled baker against identical inputs at distinct roots."""
import argparse, json, pathlib, shutil, subprocess, tempfile
p = argparse.ArgumentParser()
p.add_argument('--baker', required=True)
p.add_argument('--briefs', required=True)
p.add_argument('--expect-root-dependent', action='store_true', help='Old-generator sensitivity only; never positive qualification')
a = p.parse_args()
baker = str(pathlib.Path(a.baker).resolve(strict=True))
source = pathlib.Path(a.briefs).resolve(strict=True)

def payload(raw):
    marker = b'BUILT_IN_BRIEF_INDEX_JSON'
    # Compare complete generated Nim bytes first; parse the embedded actual JSON
    # only to establish that valid and invalid fixtures really exercised the baker.
    start = raw.index(b'{', raw.index(marker))
    value, _ = json.JSONDecoder().raw_decode(raw[start:].decode())
    return value

with tempfile.TemporaryDirectory(prefix='brief-root-equivalence-') as tmp:
    base = pathlib.Path(tmp)
    valid_relative = None
    for mode in ('valid', 'malformed-and-duplicate'):
        outputs = []
        values = []
        for name in ('first-location', 'different/deeper-location'):
            root = base / mode / name
            shutil.copytree(source, root)
            if mode != 'valid':
                assert valid_relative is not None
                candidate = root / valid_relative
                assert candidate.is_file(), 'duplicate control must copy an actually indexed valid brief'
                shutil.copyfile(candidate, root / 'duplicate-control.md')
                (root / 'malformed-control.md').write_text('---\nnot: [valid\n---\ninvalid control\n')
            output = root.parent / (root.name + '.nim')
            subprocess.run([baker, '--briefs:' + str(root), '--out:' + str(output)], check=True)
            raw = output.read_bytes()
            outputs.append(raw)
            values.append(payload(raw))
            if mode == 'valid' and valid_relative is None:
                assert values[-1]['briefs'], 'valid control must index actual fixture briefs'
                selected = pathlib.Path(values[-1]['briefs'][0]['sourceFile'])
                valid_relative = selected.relative_to(root) if selected.is_absolute() else selected
        if a.expect_root_dependent:
            assert outputs[0] != outputs[1], mode + ': old generator negative did not detect root dependence'
        else:
            assert outputs[0] == outputs[1], mode + ': absolute root changed generated artifact'
        if mode == 'valid':
            assert values[0]['briefs'], 'valid control must index real briefs'
        else:
            assert values[0]['errors'], 'invalid control must retain diagnostic reasons'
            assert any('duplicate' in e['message'] for e in values[0]['errors'])
            assert any(e['path'].replace('\\', '/').endswith('malformed-control.md') and e['message'].strip() for e in values[0]['errors']), 'malformed control must produce its own actual diagnostic'
        for brief in values[0]['briefs']:
            assert pathlib.PurePosixPath(brief['sourceFile']).is_absolute() == a.expect_root_dependent
        for error in values[0]['errors']:
            assert pathlib.PurePosixPath(error['path']).is_absolute() == a.expect_root_dependent
    print('PASS: old root-dependent negative' if a.expect_root_dependent else 'PASS: complete generated bytes equal across two roots for valid and invalid inputs')

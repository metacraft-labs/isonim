const RepoRootHere = currentSourcePath().parentDir().parentDir()
const IsonimReviewBin = RepoRootHere / "build" / "bin" / "isonim-review"

proc shouldHave(path: string) =
  if not fileExists(path):
    raise newException(IOError,
      "test_design_review_cli_seed_run: binary not found at " & path &
      ".  Build it with `just isonim-review-build`.")

proc tmpWs(suffix: string): string =
  result = getTempDir() / ("isonim_seed_run_" & suffix & "_" &
                            $epochTime().int)
  removeDir(result)
  createDir(result)

const FixtureBriefYaml = """---
briefId: render.task-app
schemaVersion: 1
kind: render
title: Task App
coversPreviews:
  - storyRef: { group: G, name: N, kind: page, index: 0 }
    backends: [web, tui, gpui, freya, cocoa, android, ios]
captureViewports:
  - { width: 1080, height: 720, label: tablet }
reviewerSchemaVersion: 1
scoringDimensions:
  - { id: a, label: A, weight: 1.0, scale: { min: 0, max: 10 } }
---
SEEDED_BRIEF_BODY_MARKER
"""

proc seedWorkspace(ws: string) =
  ## Write a brief into ``ws/briefs/render/task-app.md`` — no git
  ## init / manifest XML required for the seeded path.
  createDir(ws / "briefs" / "render")
  writeFile(ws / "briefs" / "render" / "task-app.md", FixtureBriefYaml)

proc writeConfig(workspaceRoot, storePath: string; pgPort: int): string =
  let cfgPath = workspaceRoot / "config.toml"
  writeFile(cfgPath,
    "[db]\nhost = \"127.0.0.1\"\nport = " & $pgPort &
    "\ndatabase = \"isonim_design_review\"\n" &
    "url = \"postgres://design_review_app@127.0.0.1:" & $pgPort &
    "/isonim_design_review\"\n" &
    "[store]\npath = \"" & storePath & "\"\n" &
    "[workspace]\nroot = \"" & workspaceRoot & "\"\n")
  cfgPath

proc runIsonimReview(args: seq[string]; cwd: string):
                     tuple[exitCode: int; stdout, stderr: string] =
  var environ = newStringTable(modeCaseSensitive)
  for kv in envPairs():
    environ[kv.key] = kv.value
  let p = startProcess(IsonimReviewBin, args = args,
                       workingDir = cwd, env = environ,
                       options = {poUsePath})
  let code = p.waitForExit()
  let so = p.outputStream.readAll()
  let se = p.errorStream.readAll()
  p.close()
  (exitCode: code, stdout: so, stderr: se)

proc openAppConn(pgPort: int): DbConn =
  open("", "design_review_app", "",
       "host=127.0.0.1 port=" & $pgPort &
       " dbname=isonim_design_review user=design_review_app")

proc openMigConn(pgPort: int): DbConn =
  open("", "design_review_migrator", "",
       "host=127.0.0.1 port=" & $pgPort &
       " dbname=isonim_design_review user=design_review_migrator")

# A 1x1 RGBA PNG (synthetic; just enough to pass the PNG signature +
# IHDR validation in cmd_seed_run.validatePng).  Generated by hand
# rather than via the in-tree png_codec to keep the test independent
# of that module's encoder.
const PngOnePx = [
  byte(0x89), byte(0x50), byte(0x4E), byte(0x47),
  byte(0x0D), byte(0x0A), byte(0x1A), byte(0x0A),
  # IHDR length=13
  byte(0x00), byte(0x00), byte(0x00), byte(0x0D),
  byte('I'), byte('H'), byte('D'), byte('R'),
  # width = 1
  byte(0x00), byte(0x00), byte(0x00), byte(0x01),
  # height = 1
  byte(0x00), byte(0x00), byte(0x00), byte(0x01),
  # bit depth 8, color type 6 (RGBA), compression 0, filter 0, interlace 0
  byte(0x08), byte(0x06), byte(0x00), byte(0x00), byte(0x00),
  # IHDR CRC (computed: 0x1F15C489)
  byte(0x1F), byte(0x15), byte(0xC4), byte(0x89),
  # IDAT length=16
  byte(0x00), byte(0x00), byte(0x00), byte(0x10),
  byte('I'), byte('D'), byte('A'), byte('T'),
  # zlib stream (stored block, 4 bytes raw: filter byte + RGBA pixel)
  byte(0x78), byte(0x01), byte(0x01), byte(0x05), byte(0x00),
  byte(0xFA), byte(0xFF), byte(0x00), byte(0xFF), byte(0x00),
  byte(0x00), byte(0xFF), byte(0x00), byte(0x09), byte(0x00),
  byte(0x04),
  # IDAT CRC (not validated by our codec — pad with zeros)
  byte(0x00), byte(0x00), byte(0x00), byte(0x00),
  # IEND length=0
  byte(0x00), byte(0x00), byte(0x00), byte(0x00),
  byte('I'), byte('E'), byte('N'), byte('D'),
  # IEND CRC
  byte(0xAE), byte(0x42), byte(0x60), byte(0x82),
]

proc writePngFixture(ws: string; backend: string; tag: int): string =
  ## Write a unique PNG for ``backend`` to ``ws/png/<backend>.png``.
  ## ``tag`` is mixed into one byte of the PNG payload to keep each
  ## fixture's sha256 distinct so we exercise the content-addressed
  ## store on a real branch.
  createDir(ws / "png")
  let path = ws / "png" / (backend & ".png")
  var bytes = newSeq[byte](PngOnePx.len)
  for i in 0 ..< PngOnePx.len: bytes[i] = PngOnePx[i]
  # Mutate the IDAT payload byte — survives the validatePng signature
  # check (only the first 24 bytes are inspected) and makes the sha
  # different per file.
  bytes[44] = byte(tag and 0xFF)
  var asStr = newString(bytes.len)
  for i in 0 ..< bytes.len: asStr[i] = char(bytes[i])
  writeFile(path, asStr)
  path


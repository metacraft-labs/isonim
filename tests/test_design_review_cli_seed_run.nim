proc lastNonEmpty(s: string): string =
  for line in s.splitLines():
    let stripped = line.strip()
    if stripped.len > 0:
      result = stripped

suite "Follow-up 3 — isonim-review seed-run":

  setup:
    shouldHave(IsonimReviewBin)

  test "test_seed_run_creates_run_and_captures":
    ## Three different PNGs for three backends produce one run row +
    ## three captures rows, all addressed by their sha256 in the
    ## content-addressed store.
    let pgf = newPgFixture()
    defer: pgf.shutdown()
    let ws = tmpWs("create")
    defer: removeDir(ws)
    seedWorkspace(ws)
    let storePath = ws / "review-store"
    let cfg = writeConfig(ws, storePath, pgf.port)

    let webPng = writePngFixture(ws, "web", 1)
    let tuiPng = writePngFixture(ws, "tui", 2)
    let androidPng = writePngFixture(ws, "android", 3)

    let res = runIsonimReview(@[
      "seed-run", "--brief", "render.task-app",
      "--capture", "web=" & webPng,
      "--capture", "tui=" & tuiPng,
      "--capture", "android=" & androidPng,
      "--workspace", ws,
      "--project", ws,
      "--config", cfg], cwd = ws)
    if res.exitCode != 0:
      echo "stdout:\n" & res.stdout
      echo "stderr:\n" & res.stderr
    check res.exitCode == 0

    let runId = lastNonEmpty(res.stdout)
    check runId.len == 36   # UUID

    let migConn = openMigConn(pgf.port)
    defer: migConn.close()
    let nRuns = parseInt(migConn.getValue(sql(
      "SELECT count(*) FROM design_review.runs " &
      "WHERE run_id = '" & runId & "'::uuid")))
    check nRuns == 1
    let nCaps = parseInt(migConn.getValue(sql(
      "SELECT count(*) FROM design_review.captures " &
      "WHERE run_id = '" & runId & "'::uuid")))
    check nCaps == 3

    # The three captures must each be content-addressed under the
    # configured store path.
    for backend in ["web", "tui", "android"]:
      let pngPath = migConn.getValue(sql(
        "SELECT png_path FROM design_review.captures " &
        "WHERE run_id = '" & runId & "'::uuid AND backend = '" &
        backend & "'"))
      check pngPath.startsWith(storePath)
      check fileExists(pngPath)

  test "test_seed_run_rejects_missing_png":
    ## Non-existent PNG path → non-zero exit + no DB rows.
    let pgf = newPgFixture()
    defer: pgf.shutdown()
    let ws = tmpWs("missing")
    defer: removeDir(ws)
    seedWorkspace(ws)
    let storePath = ws / "review-store"
    let cfg = writeConfig(ws, storePath, pgf.port)

    let res = runIsonimReview(@[
      "seed-run", "--brief", "render.task-app",
      "--capture", "web=" & ws / "does-not-exist.png",
      "--workspace", ws,
      "--project", ws,
      "--config", cfg], cwd = ws)
    check res.exitCode != 0

    let migConn = openMigConn(pgf.port)
    defer: migConn.close()
    let nRuns = parseInt(migConn.getValue(sql(
      "SELECT count(*) FROM design_review.runs")))
    check nRuns == 0

  test "test_seed_run_rejects_non_png_file":
    ## A text file masquerading as a PNG is caught by validatePng's
    ## signature check.  Exit non-zero, message mentions "not a valid PNG".
    let pgf = newPgFixture()
    defer: pgf.shutdown()
    let ws = tmpWs("textfile")
    defer: removeDir(ws)
    seedWorkspace(ws)
    let storePath = ws / "review-store"
    let cfg = writeConfig(ws, storePath, pgf.port)

    let fakePng = ws / "fake.png"
    writeFile(fakePng, "this is not a PNG, sorry!\n")

    let res = runIsonimReview(@[
      "seed-run", "--brief", "render.task-app",
      "--capture", "web=" & fakePng,
      "--workspace", ws,
      "--project", ws,
      "--config", cfg], cwd = ws)
    check res.exitCode != 0
    check (res.stdout & res.stderr).contains("not a valid PNG")

    let migConn = openMigConn(pgf.port)
    defer: migConn.close()
    let nRuns = parseInt(migConn.getValue(sql(
      "SELECT count(*) FROM design_review.runs")))
    check nRuns == 0

  test "test_seed_run_uses_seeded_manifest_hash":
    ## The run's ``manifest_hash`` column must start with ``seeded:``
    ## and embed the operator-supplied tag.
    let pgf = newPgFixture()
    defer: pgf.shutdown()
    let ws = tmpWs("hash")
    defer: removeDir(ws)
    seedWorkspace(ws)
    let storePath = ws / "review-store"
    let cfg = writeConfig(ws, storePath, pgf.port)
    let webPng = writePngFixture(ws, "web", 7)

    let res = runIsonimReview(@[
      "seed-run", "--brief", "render.task-app",
      "--capture", "web=" & webPng,
      "--manifest-hash-tag", "m-evp-14-historical",
      "--workspace", ws,
      "--project", ws,
      "--config", cfg], cwd = ws)
    check res.exitCode == 0
    let runId = lastNonEmpty(res.stdout)

    let migConn = openMigConn(pgf.port)
    defer: migConn.close()
    let hash = migConn.getValue(sql(
      "SELECT manifest_hash FROM design_review.runs " &
      "WHERE run_id = '" & runId & "'::uuid"))
    check hash == "seeded:m-evp-14-historical"
    check isSeededManifestHash(hash)

  test "test_brief_at_revision_falls_back_for_seeded_run":
    ## With ``manifestHash = "seeded:foo"`` the resolver must read the
    ## brief straight from the working tree — no manifest XML, no
    ## ``git show`` plumbing required.
    let ws = tmpWs("bav")
    defer: removeDir(ws)
    seedWorkspace(ws)
    let body = briefAtRevision(ws, "seeded:foo", "render.task-app")
    check body.contains("SEEDED_BRIEF_BODY_MARKER")
    check body.contains("briefId: render.task-app")

  test "e2e_seed_run_then_run_review":
    ## Full loop: seed seven backends, then drive run-review against
    ## a canned reviewer output.  Assert the agent_report row lands
    ## in the DB.
    let pgf = newPgFixture()
    defer: pgf.shutdown()
    let ws = tmpWs("e2e")
    defer: removeDir(ws)
    seedWorkspace(ws)
    let storePath = ws / "review-store"
    let cfg = writeConfig(ws, storePath, pgf.port)

    var captureArgs: seq[string] = @["seed-run",
      "--brief", "render.task-app"]
    var tag = 10
    for backend in ["web", "tui", "gpui", "freya", "cocoa",
                    "android", "ios"]:
      let pngPath = writePngFixture(ws, backend, tag)
      inc tag
      captureArgs.add "--capture"
      captureArgs.add backend & "=" & pngPath
    captureArgs.add "--workspace"; captureArgs.add ws
    captureArgs.add "--project"; captureArgs.add ws
    captureArgs.add "--config"; captureArgs.add cfg

    let seed = runIsonimReview(captureArgs, cwd = ws)
    if seed.exitCode != 0:
      echo "seed stdout:\n" & seed.stdout
      echo "seed stderr:\n" & seed.stderr
    check seed.exitCode == 0
    let runId = lastNonEmpty(seed.stdout)

    let migConn = openMigConn(pgf.port)
    defer: migConn.close()
    let nCaps = parseInt(migConn.getValue(sql(
      "SELECT count(*) FROM design_review.captures " &
      "WHERE run_id = '" & runId & "'::uuid")))
    check nCaps == 7

    # Canned reviewer output — schema matches the e2e_run_review tests.
    let cannedPath = ws / "canned.md"
    let cannedBody = "---\n" &
      "reviewerSchemaVersion: 1\n" &
      "briefId: render.task-app\n" &
      "runId: " & runId & "\n" &
      "agentName: canned\n" &
      "agentVersion: v1\n" &
      "manifestHash: seeded:test\n" &
      "capturedAt: 2026-05-19T11:32:04Z\n" &
      "overall:\n  score: 8.0\n  status: pass\n" &
      "previews:\n" &
      "  \"G/N:page#0@web\":\n" &
      "    scores: { a: 8 }\n" &
      "    status: pass\n" &
      "    defects: []\n" &
      "---\nbody\n"
    writeFile(cannedPath, cannedBody)

    let review = runIsonimReview(@[
      "run-review", "--run", runId,
      "--agent-backend", "canned",
      "--canned-path", cannedPath,
      "--agent-name", "canned",
      "--agent-version", "v1",
      "--workspace", ws,
      "--project", ws,
      "--config", cfg], cwd = ws)
    if review.exitCode != 0:
      echo "review stdout:\n" & review.stdout
      echo "review stderr:\n" & review.stderr
    check review.exitCode == 0

    let nReports = parseInt(migConn.getValue(sql(
      "SELECT count(*) FROM design_review.agent_reports " &
      "WHERE run_id = '" & runId & "'::uuid")))
    check nReports == 1

    let parsed = parseJson(migConn.getValue(sql(
      "SELECT parsed_scores::text FROM design_review.agent_reports " &
      "WHERE run_id = '" & runId & "'::uuid")))
    check parsed["overall"]["status"].getStr == "pass"

    let rawPath = storePath / "reports" / runId / "canned.md"
    check fileExists(rawPath)

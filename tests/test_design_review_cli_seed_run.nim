## Follow-up 3 — ``isonim-review seed-run`` end-to-end tests.
##
## Drives the real ``isonim-review`` binary against an ephemeral
## ``PgFixture`` and a synthetic workspace.  Each test seeds a run
## from one or more fixture PNGs, then asserts the rows in
## ``design_review.runs`` / ``design_review.captures`` and the bytes
## on disk under the configured capture store.
##
## The final ``e2e_seed_run_then_run_review`` test rounds the loop:
## after seeding the run it invokes ``run-review --run <id>
## --agent-backend canned`` and checks the agent-report row lands
## in the DB.  That exercises the ``briefAtRevision`` seeded
## fallback in the path that production reviews take.

